object ExcelMenuParser {

    private val nonVegKeywords = listOf(
        "chicken", "egg", "fish", "mutton", "prawn", "omelet", "omlette",
        "bhurji", "kheema", "non-veg", "boiled egg", "chicken curry", "chicken 65",
        "tandoori", "chilly chicken", "chicken fry", "butter chicken"
    )

    private val specialKeywords = listOf(
        "paneer", "paneer butter masala", "shahi paneer", "kadai paneer",
        "dum biryani", "ice cream", "gulab jamun", "rasgulla", "kheer",
        "malai kofta", "special dessert", "pasta", "gobi manchurian", "chilli paneer",
        "veg manchurian", "fried rice", "schezwan", "chole bhature", "pav bhaji",
        "malabar parotta", "halwa", "mysore pak", "feast", "special"
    )

    private val commonKeywords = listOf(
        "steamed rice", "white rice", "boiled rice", "chapati", "roti", "phulka",
        "papad", "pickle", "curd", "buttermilk", "plain rice", "banana", "tea",
        "coffee", "milk", "bread", "butter", "jam", "water", "hot water", "sambar", "rasam"
    )

    fun categorizeDish(dishName: String): DishCategory {
        val lower = dishName.lowercase().trim()

        for (kw in nonVegKeywords) {
            if (lower.contains(kw)) return DishCategory.NON_VEG
        }
        for (kw in specialKeywords) {
            if (lower.contains(kw)) return DishCategory.SPECIAL
        }
        for (kw in commonKeywords) {
            if (lower.contains(kw)) return DishCategory.COMMON
        }
        return DishCategory.VEG
    }

    /**
     * Processed Mess Plan Menu generated by the API
     */
    data class GeneratedMessPlanMenu(
        val id: String = UUID.randomUUID().toString(),
        val date: String,
        val messPlan: MessPlan,
        val mealType: MealType,
        var dishesSummary: String,
        var isFeast: Boolean = false,
        var specialNote: String = ""
    )

    /**
     * AI & Heuristic Parser API:
     * Takes raw spreadsheet lines (Date, Breakfast, Lunch, Snacks, Dinner)
     * and automatically generates separated menus for:
     * - Veg Mess 🥦
     * - Non-Veg Mess 🍗
     * - Special Mess ✨
     */
    fun processSpreadsheetToMessPlans(csvContent: String): List<GeneratedMessPlanMenu> {
        val results = mutableListOf<GeneratedMessPlanMenu>()
        val lines = csvContent.lines()

        for (line in lines) {
            val trimmed = line.trim()
            if (trimmed.isEmpty() || trimmed.startsWith("#") || trimmed.lowercase().startsWith("date,")) {
                continue
            }
            val parts = trimmed.split(",").map { it.trim().removeSurrounding("\"") }
            if (parts.size >= 2) {
                val date = parts[0]
                val mealStr = parts[1].uppercase()
                val mealType = when {
                    mealStr.contains("BREAKFAST") -> MealType.BREAKFAST
                    mealStr.contains("LUNCH") -> MealType.LUNCH
                    mealStr.contains("SNACK") -> MealType.SNACKS
                    mealStr.contains("DINNER") -> MealType.DINNER
                    else -> MealType.LUNCH
                }
                val rawDishes = parts.getOrNull(2) ?: "Rice; Dal; Curry"
                val dishList = rawDishes.split(";", "|", "/").map { it.trim() }.filter { it.isNotEmpty() }

                val vegDishes = mutableListOf<String>()
                val nonVegDishes = mutableListOf<String>()
                val specialDishes = mutableListOf<String>()

                for (dish in dishList) {
                    when (categorizeDish(dish)) {
                        DishCategory.NON_VEG -> {
                            nonVegDishes.add(dish)
                        }
                        DishCategory.SPECIAL -> {
                            specialDishes.add(dish)
                            vegDishes.add(dish) // specials usually enjoyed in veg or executive
                        }
                        DishCategory.COMMON -> {
                            vegDishes.add(dish)
                            nonVegDishes.add(dish)
                            specialDishes.add(dish)
                        }
                        DishCategory.VEG -> {
                            vegDishes.add(dish)
                            nonVegDishes.add(dish)
                            specialDishes.add(dish)
                        }
                    }
                }

                val isFeastDay = dishList.any { it.lowercase().contains("biryani") || it.lowercase().contains("jamun") || it.lowercase().contains("ice cream") }

                // 1. Veg Mess Menu
                results.add(
                    GeneratedMessPlanMenu(
                        date = date,
                        messPlan = MessPlan.VEG,
                        mealType = mealType,
                        dishesSummary = vegDishes.joinToString(", ").ifEmpty { "Steamed Rice, Dal, Chapati, Curd" },
                        isFeast = isFeastDay,
                        specialNote = if (isFeastDay) "Paneer Butter Masala & Gulab Jamun" else ""
                    )
                )

                // 2. Non-Veg Mess Menu
                results.add(
                    GeneratedMessPlanMenu(
                        date = date,
                        messPlan = MessPlan.NON_VEG,
                        mealType = mealType,
                        dishesSummary = (vegDishes + nonVegDishes).distinct().joinToString(", ").ifEmpty { "Steamed Rice, Chicken Curry, Chapati" },
                        isFeast = isFeastDay,
                        specialNote = if (isFeastDay) "Chicken Dum Biryani & Gulab Jamun Feast" else ""
                    )
                )

                // 3. Special Mess Menu
                results.add(
                    GeneratedMessPlanMenu(
                        date = date,
                        messPlan = MessPlan.SPECIAL,
                        mealType = mealType,
                        dishesSummary = (specialDishes + nonVegDishes + vegDishes).distinct().joinToString(", ").ifEmpty { "Executive Buffet: Biryani, Paneer, Ice Cream, Juices" },
                        isFeast = true,
                        specialNote = "Executive Live Counter & Dessert"
                    )
                )
            }
        }
        return results
    }

